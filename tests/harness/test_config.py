"""Settings: the table, the derived values, and what is exported to the checks."""

from __future__ import annotations

import pytest

from harness.config import (
    IMAGES_ENV_DEPLOYED_MARKER,
    SETTINGS,
    Settings,
    is_deployed_record,
    record_lines,
    record_values,
)


def test_every_setting_has_a_distinct_option_and_variable():
    options = [setting.option for setting in SETTINGS]
    variables = [setting.envvar for setting in SETTINGS]
    assert len(set(options)) == len(options)
    assert len(set(variables)) == len(variables)


def test_defaults_match_the_harness_this_replaces():
    settings = Settings()
    assert settings.kind_cluster == "trustyai"
    assert settings.kube_context == "kind-trustyai"
    assert settings.namespace == "system"
    assert settings.tag == "dev"
    assert settings.image_prefix == "localhost"
    assert settings.registry_port == "5005"
    assert settings.trustyai_service_img == "quay.io/trustyai/trustyai-service:latest"
    assert settings.report_file == "reports/report.html"
    assert settings.adapters_report_file == "reports/adapters.html"


def test_image_references_are_derived_from_prefix_and_tag():
    settings = Settings(image_prefix="registry.example", tag="pr-12")
    assert settings.workload_img == "registry.example/trustyai-service-operator:pr-12"
    assert settings.module_img == "registry.example/trustyai-operator-module:pr-12"


def test_an_image_named_outright_survives_a_new_tag():
    settings = Settings(workload_img="quay.io/me/operator:mine").with_updates(tag="next")
    assert settings.workload_img == "quay.io/me/operator:mine"
    assert settings.module_img == "localhost/trustyai-operator-module:next"


def test_image_record_only_fills_what_the_caller_left_alone():
    settings = Settings().with_updates(evalhub_img="quay.io/me/evalhub:mine")
    merged = settings.with_image_record(
        {
            "WORKLOAD_IMG": "localhost:5005/trustyai-service-operator:dev",
            "MODULE_IMG": "localhost:5005/trustyai-operator-module:dev",
            "EVALHUB_IMG": "localhost:5005/evalhub/evalhub:dev",
            "LMES_IMG": "",
        }
    )
    assert merged.workload_img == "localhost:5005/trustyai-service-operator:dev"
    assert merged.evalhub_img == "quay.io/me/evalhub:mine"
    assert merged.lmes_img == ""


def test_a_variable_in_the_environment_counts_as_named():
    settings = Settings.from_params({"evalhub_img": "quay.io/me/evalhub:from-env"})
    merged = settings.with_image_record({"EVALHUB_IMG": "localhost:5005/evalhub/evalhub:dev"})
    assert merged.evalhub_img == "quay.io/me/evalhub:from-env"


def test_export_publishes_the_resolved_values(monkeypatch):
    for setting in SETTINGS:
        monkeypatch.delenv(setting.envvar, raising=False)
    settings = Settings.from_params({"namespace": "opendatahub", "kind_cluster": "other"})
    settings.export()
    import os

    assert os.environ["NAMESPACE"] == "opendatahub"
    assert os.environ["KUBE_CONTEXT"] == "kind-other"
    assert os.environ["KEEP_RESOURCES"] == ""
    assert os.environ["IMAGES_ENV_FILE"].endswith("reports/images.env")
    assert os.path.isabs(os.environ["IMAGES_ENV_FILE"])


def test_export_publishes_switches_as_one(monkeypatch):
    settings = Settings.from_params({"skip_build": True, "remove_after_push": False})
    settings.export()
    import os

    assert os.environ["SKIP_BUILD"] == "1"
    assert os.environ["REMOVE_AFTER_PUSH"] == ""


def test_images_env_path_follows_the_setting(tmp_path, monkeypatch):
    absolute = tmp_path / "images.env"
    assert Settings(images_env_file=str(absolute)).images_env_path == absolute
    relative = Settings(images_env_file="reports/other.env").images_env_path
    assert relative.is_absolute()
    assert relative.name == "other.env"

    # Without a checkout the record lives where the command was run.
    monkeypatch.setattr("harness.config.repository_root", lambda: None)
    monkeypatch.chdir(tmp_path)
    assert Settings(images_env_file="reports/other.env").images_env_path == tmp_path / "reports" / "other.env"


def test_record_round_trip(tmp_path):
    path = tmp_path / "images.env"
    path.write_text(
        "\n".join(
            [
                "# Generated by k8s-tests images-all: images pushed to localhost:5005",
                "WORKLOAD_IMG=localhost:5005/trustyai-service-operator:dev",
                "",
                "LMES_IMG=localhost:5005/evalhub/community-lmes:dev",
            ]
        )
    )
    assert record_values(path) == {
        "WORKLOAD_IMG": "localhost:5005/trustyai-service-operator:dev",
        "LMES_IMG": "localhost:5005/evalhub/community-lmes:dev",
    }
    assert record_lines(path) == [
        "WORKLOAD_IMG=localhost:5005/trustyai-service-operator:dev",
        "LMES_IMG=localhost:5005/evalhub/community-lmes:dev",
    ]
    assert not is_deployed_record(path)

    path.write_text("\n".join([f"# {IMAGES_ENV_DEPLOYED_MARKER}", *record_lines(path)]))
    assert is_deployed_record(path)


def test_a_missing_record_reads_as_empty(tmp_path):
    assert record_values(tmp_path / "absent.env") == {}
    assert not is_deployed_record(tmp_path / "absent.env")


