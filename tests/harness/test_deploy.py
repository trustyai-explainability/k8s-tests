def test_an_apply_that_fails_without_a_conflict_stops_the_run(tmp_path, monkeypatch):
    """A non-zero apply that is not a recoverable conflict is a failure, not a clean apply."""
    import subprocess

    from harness import deploy as deploy_module

    calls: list[list[str]] = []

    def kube_result(settings, *args, **kwargs):
        calls.append([str(argument) for argument in args])
        return subprocess.CompletedProcess(calls[-1], 1, "", "error: clusterroles is forbidden")

    monkeypatch.setattr(deploy_module, "kube_result", kube_result)
    with pytest.raises(HarnessError, match="exit status 1"):
        deploy_module.apply_overlay(Settings(), tmp_path)
    assert len(calls) == 1


def test_a_forced_reapply_that_fails_for_another_reason_stops_the_run(tmp_path, monkeypatch):
    """Forcing the conflict away recovers it only when the retry itself succeeds."""
    import subprocess

    from harness import deploy as deploy_module

    calls: list[list[str]] = []

    def kube_result(settings, *args, **kwargs):
        argv = [str(argument) for argument in args]
        calls.append(argv)
        if len(calls) == 1:
            return subprocess.CompletedProcess(argv, 1, "", 'Apply failed with 1 conflict: conflict with "x": .rules')
        return subprocess.CompletedProcess(argv, 1, "", "error: the server does not allow access to the resource")

    monkeypatch.setattr(deploy_module, "kube_result", kube_result)
    with pytest.raises(HarnessError, match="--force-conflicts failed with exit status 1"):
        deploy_module.apply_overlay(Settings(), tmp_path)
    assert len(calls) == 2


def test_every_applied_crd_is_waited_for(tmp_path, monkeypatch):
    """The Prometheus CRD is a stand-in too, and its CR is applied after this step."""
    from pathlib import Path

    from harness import arch
    from harness import deploy as deploy_module

    crds = tmp_path / "tests" / "crds"
    crds.mkdir(parents=True)
    entries = deploy_module.crd_entries(Settings(operator_arch=arch.ARCH_MODULAR))
    for filename, _ in entries:
        (crds / filename).write_text("kind: CustomResourceDefinition\n")

    commands: list[list[str]] = []
    monkeypatch.setattr(deploy_module, "operator_repo", lambda settings: tmp_path)
    monkeypatch.setattr(deploy_module, "kube", lambda settings, *args, **kwargs: commands.append(list(args)) or "")

    deploy_module.apply_external_crds(Settings(operator_arch=arch.ARCH_MODULAR))

    applied = [Path(str(arg)).name for command in commands for arg in command if str(arg).endswith(".yaml")]
    assert sorted(applied) == sorted(filename for filename, _ in entries)
    waited = [command[-2] for command in commands if command[0] == "wait"]
    assert sorted(waited) == sorted(f"crd/{name}" for _, name in entries)


def test_the_single_layout_points_the_conversion_webhooks(monkeypatch, tmp_path):
    """The webhook CA is what `utilities.stack` does on the modular layout."""
    from harness import arch
    from harness import deploy as deploy_module

    order: list[str] = []
    monkeypatch.setattr(arch, "require_operator_repo", lambda settings: tmp_path)
    monkeypatch.setattr(arch, "operator_arch", lambda settings: arch.ARCH_SINGLE)
    monkeypatch.setattr(deploy_module, "keep_used_images", lambda settings: None)
    monkeypatch.setattr(deploy_module, "ensure_namespace", lambda settings: order.append("namespace"))
    monkeypatch.setattr(deploy_module, "apply_external_crds", lambda settings: order.append("crds"))
    monkeypatch.setattr(deploy_module, "deploy_single", lambda settings, path: order.append("single"))
    monkeypatch.setattr(deploy_module, "point_conversion_webhooks", lambda settings: order.append("webhooks"))
    monkeypatch.setattr(deploy_module, "bring_up", lambda settings: order.append("bring-up"))
    monkeypatch.setattr(deploy_module, "stamp_record", lambda settings, kept: None)

    deploy_module.deploy(Settings(), next_step=False)
    assert order == ["namespace", "crds", "single", "webhooks"]


